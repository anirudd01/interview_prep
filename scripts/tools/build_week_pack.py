"""
Build a single NotebookLM source file for one week of teaching.
================================================================

NotebookLM audio is most useful when it covers exactly what you're learning that
week. Uploading whole answer files (100+ questions) dilutes it. This script reads a
lesson plan in teach/, finds its fenced ```pack block, pulls exactly those numbered
answers out of answers/*.md, and writes one Markdown file to upload:

    notebooklm/<lesson-plan-name>_pack.md  =  lesson plan  +  the selected answers

Pack block format (inside the lesson plan):

    ```pack
    answers/ROUND_2_fundamentals_breadth_answers.md: 1-6, 8, 9
    answers/ROUND_3_python_and_backend_advanced_answers.md: 12
    scripts/async/README.md: all
    ```

Answers are found by their "### <n>." headings. A section runs until the next "##"
or "###" heading outside a code fence. "all" includes the whole file.

Usage (from the repo root):
    python scripts/tools/build_week_pack.py teach/W01_python_core.md
    python scripts/tools/build_week_pack.py teach/W0*.md        # several at once

Stdlib only.
"""

import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
OUT_DIR = REPO / "notebooklm"
HEADING = re.compile(r"^#{2,3} ")
QUESTION = re.compile(r"^### (\d+)\.")


def parse_spec(spec: str) -> set[int] | None:
    """'1-6, 8, 9' -> {1..6, 8, 9}; 'all' -> None (meaning the whole file)."""
    if spec.strip().lower() == "all":
        return None
    nums: set[int] = set()
    for part in spec.split(","):
        part = part.strip()
        if not part:
            continue
        if "-" in part:
            lo, hi = (int(x) for x in part.split("-", 1))
            nums.update(range(lo, hi + 1))
        else:
            nums.add(int(part))
    return nums


def read_pack_block(plan_text: str) -> list[tuple[str, set[int] | None]]:
    m = re.search(r"```pack\n(.*?)```", plan_text, re.S)
    if not m:
        raise SystemExit("no ```pack block found in the lesson plan")
    entries = []
    for line in m.group(1).splitlines():
        if line.strip() and not line.lstrip().startswith("#"):
            path, spec = line.rsplit(":", 1)
            entries.append((path.strip(), parse_spec(spec)))
    return entries


def extract_questions(text: str, wanted: set[int]) -> tuple[list[str], set[int]]:
    """Return the selected '### n.' sections (in file order) and the numbers found."""
    sections: list[str] = []
    found: set[int] = set()
    current: list[str] | None = None
    in_fence = False
    for line in text.splitlines():
        if line.lstrip().startswith("```"):
            in_fence = not in_fence
        if not in_fence and HEADING.match(line):
            if current is not None:          # a heading ends the open section
                sections.append("\n".join(current).rstrip())
                current = None
            q = QUESTION.match(line)
            if q and int(q.group(1)) in wanted:
                found.add(int(q.group(1)))
                current = [line]
                continue
        if current is not None:
            current.append(line)
    if current is not None:
        sections.append("\n".join(current).rstrip())
    return sections, found


def build(plan_path: Path) -> Path:
    plan_text = plan_path.read_text(encoding="utf-8")
    parts = [f"# NotebookLM pack: {plan_path.stem}\n",
             "Generated by scripts/tools/build_week_pack.py. Part 1 is the lesson plan; "
             "part 2 is the reference answers for this week only.\n",
             "---\n\n# PART 1 - LESSON PLAN\n", plan_text,
             "\n---\n\n# PART 2 - REFERENCE ANSWERS\n"]
    for rel, wanted in read_pack_block(plan_text):
        src = REPO / rel
        text = src.read_text(encoding="utf-8")
        parts.append(f"\n## Source: {rel}\n")
        if wanted is None:
            parts.append(text)
            continue
        sections, found = extract_questions(text, wanted)
        missing = sorted(wanted - found)
        if missing:
            print(f"  warning: {rel}: no answer found for {missing}", file=sys.stderr)
        parts.append("\n\n".join(sections))
    OUT_DIR.mkdir(exist_ok=True)
    out = OUT_DIR / f"{plan_path.stem}_pack.md"
    out.write_text("\n".join(parts) + "\n", encoding="utf-8")
    return out


def main() -> None:
    if len(sys.argv) < 2:
        raise SystemExit(__doc__)
    for arg in sys.argv[1:]:
        out = build(Path(arg).resolve())
        size_kb = out.stat().st_size / 1024
        print(f"wrote {out.relative_to(REPO)}  ({size_kb:.0f} KB)")


if __name__ == "__main__":
    main()
